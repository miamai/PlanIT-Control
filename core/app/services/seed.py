from __future__ import annotations

from datetime import UTC, datetime, timedelta

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.config import Settings
from app.models.entities import (
    Alert,
    AlertStatus,
    HazardObservation,
    HazardType,
    QualityStatus,
    RiskScore,
    SafetyBriefing,
    Severity,
    Site,
)
from app.schemas.domain import LightningStrikeInput
from app.services.eia import import_plants, parse_cached_sites
from app.services.lightning import process_strike


async def seed_demo(session: AsyncSession, settings: Settings) -> dict[str, int]:
    imported = await import_plants(session, parse_cached_sites())
    sites = (await session.scalars(select(Site).order_by(Site.eia_plant_id).limit(6))).all()
    now = datetime.now(UTC).replace(microsecond=0)
    observations = 0
    for index, site in enumerate(sites):
        event_prefix = f"demo:{site.eia_plant_id}:{now.date()}"
        existing = await session.scalar(
            select(HazardObservation).where(
                HazardObservation.source_event_id == f"{event_prefix}:heat"
            )
        )
        if existing:
            continue
        session.add_all(
            [
                HazardObservation(
                    site_id=site.id,
                    hazard_type=HazardType.HEAT,
                    source="planit_demo",
                    source_event_id=f"{event_prefix}:heat",
                    observed_at=now,
                    metric_name="calculated_heat_index",
                    numeric_value=96 + index * 3,
                    unit="degF",
                    latitude=site.latitude,
                    longitude=site.longitude,
                    metadata_={"value_kind": "calculated", "synthetic_notice": True},
                    quality_status=QualityStatus.SYNTHETIC,
                    is_estimated=False,
                ),
                HazardObservation(
                    site_id=site.id,
                    hazard_type=HazardType.FLOOD,
                    source="planit_demo",
                    source_event_id=f"{event_prefix}:flood",
                    observed_at=now,
                    metric_name="rainfall_flood_risk_proxy",
                    numeric_value=45 + index * 5,
                    unit="mm_24h",
                    latitude=site.latitude,
                    longitude=site.longitude,
                    metadata_={"confirmed_flooding": False, "synthetic_notice": True},
                    quality_status=QualityStatus.SYNTHETIC,
                    is_estimated=True,
                ),
            ]
        )
        session.add(
            RiskScore(
                site_id=site.id,
                score=round(2.5 + index, 1),
                generated_at=now,
                valid_for_seconds=86400,
                model_version="demo-not-a-model-v1",
                score_source="demo",
                contributing_factors={"synthetic_notice": True},
            )
        )
        if index < 2:
            source_reference = f"demo-alert:{site.eia_plant_id}:{now.date()}"
            alert_exists = await session.scalar(
                select(Alert).where(Alert.source_reference == source_reference)
            )
            if not alert_exists:
                session.add(
                    Alert(
                        site_id=site.id,
                        hazard_type=HazardType.HEAT if index == 0 else HazardType.FLOOD,
                        severity=Severity.HIGH,
                        status=AlertStatus.ACTIVE,
                        title=(
                            "Synthetic heat warning"
                            if index == 0
                            else "Synthetic rainfall-based flood-risk warning"
                        ),
                        message="Demonstration alert generated by the PlanIT seed command.",
                        recommended_action="Demonstration only; follow approved site procedures.",
                        triggered_at=now,
                        source_reference=source_reference,
                        details={"synthetic_notice": True, "not_an_official_standard": True},
                    )
                )
        session.add(
            SafetyBriefing(
                site_id=site.id,
                briefing_date=(now + timedelta(days=1)).date(),
                summary=f"Synthetic demonstration briefing for {site.name}. Do not use operationally.",
                hazard_details={"synthetic_notice": True, "missing_live_sources": True},
            )
        )
        observations += 2
    await session.commit()
    if sites:
        strike = LightningStrikeInput(
            strike_id=f"demo-{sites[0].eia_plant_id}-{now:%Y%m%d}",
            latitude=sites[0].latitude + 0.03,
            longitude=sites[0].longitude,
            occurred_at=now,
            provider="planit_fixture",
            metadata={"synthetic_notice": True},
        )
        await process_strike(session, strike, settings)
        await session.commit()
    return {"sites": imported, "observations": observations}
